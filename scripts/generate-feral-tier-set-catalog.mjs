import { readFile, writeFile } from "node:fs/promises";

import { loadSimcVersionLock } from "./lib/simc-version-lock.mjs";

const sourceUrl = new URL("../vendor/simc/engine/dbc/generated/item_set_bonus.inc", import.meta.url);
const outputUrl = new URL("../demo/data/12.1/generated/feral-tier-sets.generated.js", import.meta.url);
const simcLock = await loadSimcVersionLock({ verifyVendorFiles: true });
const source = await readFile(sourceUrl, "utf8");

const rowPattern = /^\s*\{\s*"([^"]*)"\s*,\s*"([^"]*)"\s*,\s*"([^"]*)"\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*\{([^}]*)\}\s*\},/;
const rows = [];

for (const line of source.split(/\r?\n/)) {
  const match = line.match(rowPattern);
  if (!match) continue;
  const [
    , setName, setOptName, tier, enumId, setId, pieces, classId, specId, traitSubTreeId, spellId, rawItemIds,
  ] = match;
  if (Number(classId) !== 11 || Number(specId) !== 103 || !setOptName.startsWith("midnight_season_")) continue;
  rows.push({
    id: `${setOptName}_${pieces}pc`,
    setName,
    setOptName,
    tier,
    enumId: Number(enumId),
    setId: Number(setId),
    pieces: Number(pieces),
    classId: Number(classId),
    specializationId: Number(specId),
    traitSubTreeId: Number(traitSubTreeId),
    spellId: Number(spellId),
    itemIds: rawItemIds
      .split(",")
      .map((value) => Number.parseInt(value.trim(), 10))
      .filter((value) => Number.isInteger(value) && value > 0),
    source: {
      kind: "simc-generated-dbc",
      gameVersion: simcLock.wowVersion,
      simcVersion: simcLock.simcVersion,
      vendorFingerprint: simcLock.vendorFingerprint,
      sourceRef: "engine/dbc/generated/item_set_bonus.inc",
    },
  });
}

rows.sort((left, right) => left.setOptName.localeCompare(right.setOptName) || left.pieces - right.pieces);
if (rows.length < 4) throw new Error(`Expected at least four Midnight Feral tier rows, found ${rows.length}`);

const output = `// Generated by scripts/generate-feral-tier-set-catalog.mjs. Do not edit manually.\n` +
  `export const FERAL_TIER_SET_CATALOG = Object.freeze(${JSON.stringify(rows, null, 2)});\n`;
await writeFile(outputUrl, output, "utf8");
console.log(outputUrl.pathname);
