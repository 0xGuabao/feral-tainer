import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

import {
  browserVersionMetadata,
  loadSimcVersionLock,
  projectRoot,
} from "./lib/simc-version-lock.mjs";

const lock = await loadSimcVersionLock({ verifyVendorFiles: true });
const outputPath = resolve(projectRoot, "demo/data/12.1/generated/version.generated.js");
const output = `// Generated by scripts/generate-simc-version-module.mjs. Do not edit manually.\n` +
  `export const SIMC_VERSION_LOCK = Object.freeze(${JSON.stringify(browserVersionMetadata(lock), null, 2)});\n`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, output, "utf8");
console.log(outputPath);
