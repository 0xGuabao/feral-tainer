import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { loadSimcVersionLock } from "./lib/simc-version-lock.mjs";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDirectory, "..");
const sourcePath = resolve(
  projectRoot,
  "vendor/simc/engine/dbc/generated/trait_data.inc",
);
const outputPath = resolve(
  projectRoot,
  "demo/data/12.1/generated/druid-talent-tree.generated.js",
);

const DRUID_CLASS_ID = 11;
const PLAYER_TREE_MAX = 4;
const simcLock = await loadSimcVersionLock({ verifyVendorFiles: true });
const source = await readFile(sourcePath, "utf8");

const rowPattern = /\{\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*"((?:[^"\\]|\\.)*)",\s*\{([^}]*)\},\s*\{([^}]*)\},\s*(-?\d+),\s*(-?\d+)\s*\},/g;

function parseNumberList(value) {
  return value
    .split(",")
    .map((part) => Number(part.trim()))
    .filter(Number.isFinite);
}

function decodeCString(value) {
  return value.replaceAll("\\\"", "\"").replaceAll("\\\\", "\\");
}

const entries = [];
for (const match of source.matchAll(rowPattern)) {
  const [
    ,
    treeIndex,
    classId,
    entryId,
    nodeId,
    maxRanks,
    requiredPoints,
    definitionId,
    spellId,
    replaceSpellId,
    overrideSpellId,
    row,
    column,
    selectionIndex,
    encodedName,
    specIds,
    starterSpecIds,
    subtreeId,
    nodeType,
  ] = match;

  if (Number(classId) !== DRUID_CLASS_ID) continue;
  if (Number(treeIndex) < 0 || Number(treeIndex) > PLAYER_TREE_MAX) continue;

  entries.push({
    treeIndex: Number(treeIndex),
    entryId: Number(entryId),
    nodeId: Number(nodeId),
    maxRanks: Number(maxRanks),
    requiredPoints: Number(requiredPoints),
    definitionId: Number(definitionId),
    spellId: Number(spellId),
    replaceSpellId: Number(replaceSpellId),
    overrideSpellId: Number(overrideSpellId),
    row: Number(row),
    column: Number(column),
    selectionIndex: Number(selectionIndex),
    name: decodeCString(encodedName),
    specIds: parseNumberList(specIds),
    starterSpecIds: parseNumberList(starterSpecIds),
    subtreeId: Number(subtreeId),
    nodeType: Number(nodeType),
  });
}

if (!entries.length) {
  throw new Error(`No Druid talent rows parsed from ${sourcePath}`);
}

// SimC generate_tree_nodes() iterates tree enum order, preserves the generated
// data order inside each tree, and finally iterates a std::map keyed by node id.
const orderedEntries = [];
for (let treeIndex = 0; treeIndex <= PLAYER_TREE_MAX; treeIndex += 1) {
  orderedEntries.push(...entries.filter((entry) => entry.treeIndex === treeIndex));
}

const nodeMap = new Map();
for (const entry of orderedEntries) {
  if (!nodeMap.has(entry.nodeId)) {
    nodeMap.set(entry.nodeId, { nodeId: entry.nodeId, entries: [] });
  }
  nodeMap.get(entry.nodeId).entries.push(entry);
}

const nodes = [...nodeMap.values()].sort((left, right) => left.nodeId - right.nodeId);
const generated = `// Generated by scripts/generate-druid-talent-tree.mjs. Do not edit by hand.\n` +
  `// Source: vendor/simc/engine/dbc/generated/trait_data.inc\n` +
  `export const DRUID_TALENT_TREE_12_1 = Object.freeze(${JSON.stringify(
    {
      schemaVersion: 1,
      gameVersion: simcLock.wowVersion,
      simcVersion: simcLock.simcVersion,
      vendorFingerprint: simcLock.vendorFingerprint,
      classId: DRUID_CLASS_ID,
      specializationIds: { feral: 103 },
      serializationVersion: 2,
      source: "SimulationCraft trait_data.inc",
      nodes,
    },
    null,
    2,
  )});\n`;

await writeFile(outputPath, generated, "utf8");
process.stdout.write(
  `Generated ${nodes.length} nodes / ${entries.length} entries -> ${outputPath}\n`,
);
